#!/usr/bin/env node

/**
 * scripts/build-tutor-web.cjs
 *
 * Deterministic generator for self-contained AI web chat prompt.
 * Assembles canonical SKILL.md and reference documents into a single portable prompt file.
 *
 * Usage:
 *   node scripts/build-tutor-web.cjs          # Generates web-prompt.md in skills/ and .agents/
 *   node scripts/build-tutor-web.cjs --check  # Validates web-prompt.md is up-to-date (exits 1 if stale)
 */

const fs = require('node:fs');
const path = require('node:path');
const process = require('node:process');

const REPO_ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(REPO_ROOT, 'skills', 'strict-tutor');
const CANONICAL_OUT = path.join(SOURCE_DIR, 'web-prompt.md');
const AGENT_OUT = path.join(REPO_ROOT, '.agents', 'skills', 'strict-tutor', 'web-prompt.md');

const isCheck = process.argv.includes('--check');

function stripYamlFrontmatter(content) {
  if (content.startsWith('---')) {
    const endIdx = content.indexOf('\n---', 3);
    if (endIdx !== -1) {
      return content.slice(endIdx + 4).trimStart();
    }
  }
  return content;
}

function generateWebPrompt() {
  const skillMdPath = path.join(SOURCE_DIR, 'SKILL.md');
  const antiCargoCultPath = path.join(SOURCE_DIR, 'references', 'anti-cargo-cult-rules.md');
  const rubricPath = path.join(SOURCE_DIR, 'references', 'pedagogy-rubric.md');
  const sessionTemplatePath = path.join(SOURCE_DIR, 'references', 'session-template.md');

  if (!fs.existsSync(skillMdPath)) throw new Error(`Missing source file: ${skillMdPath}`);
  if (!fs.existsSync(antiCargoCultPath)) throw new Error(`Missing source file: ${antiCargoCultPath}`);
  if (!fs.existsSync(rubricPath)) throw new Error(`Missing source file: ${rubricPath}`);
  if (!fs.existsSync(sessionTemplatePath)) throw new Error(`Missing source file: ${sessionTemplatePath}`);

  let skillContent = stripYamlFrontmatter(fs.readFileSync(skillMdPath, 'utf8'));
  let antiCargoCultContent = fs.readFileSync(antiCargoCultPath, 'utf8');
  let rubricContent = fs.readFileSync(rubricPath, 'utf8');
  let sessionTemplateContent = fs.readFileSync(sessionTemplatePath, 'utf8');

  // Convert relative file links to internal anchor links
  skillContent = skillContent
    .replace(/\.\/references\/pedagogy-rubric\.md/g, '#appendix-b-pedagogical-rubrics--evidence-guidelines')
    .replace(/\.\/references\/anti-cargo-cult-rules\.md/g, '#appendix-a-anti-rote-anti-cargo-culting--recovery-heuristics')
    .replace(/\.\/references\/session-template\.md/g, '#appendix-c-tutor-session-state-schema-template');

  const parts = [
    `<!-- AUTOGENERATED FILE - DO NOT EDIT DIRECTLY. Generated via scripts/build-tutor-web.cjs -->`,
    `# Adaptive Technical Tutor & Pedagogical Companion (Web Chat Edition)`,
    ``,
    `> **Platform & Environment Note:** This document is a complete, self-contained system instruction bundle for use in AI web chat platforms (e.g. Gemini, ChatGPT, Claude, LibreChat) as well as coding assistants. In chat web interfaces where slash commands are not registered by the host application, command triggers and flags (such as \`/tutor <topic>\`, \`--practice\`, \`--teach-back\`, \`--cards\`) function as direct conversational instructions. The tutor operates completely in-context and does not require external tools, databases, or background schedulers.`,
    ``,
    skillContent.trim(),
    ``,
    `---`,
    ``,
    `## Appendix A: Anti-Rote, Anti-Cargo-Culting & Recovery Heuristics`,
    ``,
    antiCargoCultContent.trim(),
    ``,
    `---`,
    ``,
    `## Appendix B: Pedagogical Rubrics & Evidence Guidelines`,
    ``,
    rubricContent.trim(),
    ``,
    `---`,
    ``,
    `## Appendix C: Tutor Session State Schema Template`,
    ``,
    sessionTemplateContent.trim(),
    ``
  ];

  return parts.join('\n');
}

function run() {
  const expectedContent = generateWebPrompt();

  if (isCheck) {
    let hasError = false;

    for (const outPath of [CANONICAL_OUT, AGENT_OUT]) {
      if (!fs.existsSync(outPath)) {
        console.error(`[CHECK FAILED] Missing output file: ${path.relative(REPO_ROOT, outPath)}`);
        hasError = true;
        continue;
      }
      const actualContent = fs.readFileSync(outPath, 'utf8');
      if (actualContent !== expectedContent) {
        console.error(`[CHECK FAILED] Stale or modified output file: ${path.relative(REPO_ROOT, outPath)}`);
        hasError = true;
      }
    }

    if (hasError) {
      console.error('Run `node scripts/build-tutor-web.cjs` to synchronize web prompt outputs.');
      process.exit(1);
    }

    console.log('[CHECK PASSED] Both web-prompt.md artifacts are up to date and identical.');
    process.exit(0);
  }

  // Write mode
  fs.mkdirSync(path.dirname(CANONICAL_OUT), { recursive: true });
  fs.mkdirSync(path.dirname(AGENT_OUT), { recursive: true });

  fs.writeFileSync(CANONICAL_OUT, expectedContent, 'utf8');
  fs.writeFileSync(AGENT_OUT, expectedContent, 'utf8');

  console.log(`[BUILD SUCCESS] Generated:`);
  console.log(`  - ${path.relative(REPO_ROOT, CANONICAL_OUT)}`);
  console.log(`  - ${path.relative(REPO_ROOT, AGENT_OUT)}`);
}

run();
